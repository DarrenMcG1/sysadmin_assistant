async def test_endpoint_never_404s_before_the_first_nightly_job(
    test_client, mock_session
):
    """Unlike /api/units/status, this recomputes live — there is no
    stored row to be missing."""
    _rows(mock_session, [])

    response = await test_client.get("/api/services/reliability")

    assert response.status_code == 200
    assert response.json()["count"] == 4


async def test_endpoint_response_parses_as_its_contract(test_client, mock_session):
    _rows(mock_session, _checks("test-api", ["ok"] * 50 + ["critical"] * 50))

    payload = (await test_client.get("/api/services/reliability")).json()
    parsed = ReliabilityResponse.from_dict(payload)

