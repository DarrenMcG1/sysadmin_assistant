def test_summarise_over_an_empty_list_does_not_divide_by_zero():
    summary = summarise([])
    assert summary.services_scored == 0
    assert summary.mean_score == 100.0


def test_to_contract_carries_the_deductions_through():
    score = score_service(
        "svc",
        [],
        now=NOW,
    )
    info = to_contract(score)
    assert info.service == "svc"
    assert info.deductions == []
    assert info.window_start is not None
